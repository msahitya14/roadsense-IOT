#!/usr/bin/env bash
# One-time setup: creates broker users (random passwords) and firmware/include/secrets.h.
# Re-run with --force to regenerate passwords.
set -euo pipefail
cd "$(dirname "$0")"
ROOT="$(cd .. && pwd)"
SECRETS="$ROOT/firmware/include/secrets.h"

if [[ -f credentials.txt && "${1:-}" != "--force" ]]; then
  echo "credentials.txt already exists (use --force to regenerate):"; cat credentials.txt; exit 0
fi

PASSWD_BIN="$(command -v mosquitto_passwd || echo /opt/homebrew/bin/mosquitto_passwd)"
DEV_PASS="$(openssl rand -hex 8)"
DASH_PASS="$(openssl rand -hex 8)"
rm -f passwd
"$PASSWD_BIN" -c -b passwd rs01 "$DEV_PASS"
"$PASSWD_BIN" -b passwd dashboard "$DASH_PASS"
chmod 600 passwd acl
mkdir -p data

IP="$(ipconfig getifaddr en0 2>/dev/null || hostname -I 2>/dev/null | awk '{print $1}' || echo 192.168.1.50)"

cat > credentials.txt <<EOF
LAPTOP_IP=$IP
DEVICE_USER=rs01
DEVICE_PASS=$DEV_PASS
DASH_USER=dashboard
DASH_PASS=$DASH_PASS
EOF
chmod 600 credentials.txt

WIFI_SSID="your-hotspot-name"; WIFI_PASS="your-hotspot-password"
if [[ -f "$SECRETS" ]]; then   # keep Wi-Fi settings the user already filled in
  WIFI_SSID="$(sed -n 's/^#define WIFI_SSID *"\(.*\)"/\1/p' "$SECRETS")"
  WIFI_PASS="$(sed -n 's/^#define WIFI_PASS *"\(.*\)"/\1/p' "$SECRETS")"
fi
cat > "$SECRETS" <<EOF
#pragma once
// Generated by broker/setup.sh. Git-ignored. Edit WIFI_* by hand.
#define WIFI_SSID   "$WIFI_SSID"
#define WIFI_PASS   "$WIFI_PASS"
#define MQTT_HOST   "$IP"   // laptop IP; re-run setup.sh --force or edit if it changes
#define MQTT_PORT   1883
#define MQTT_USER   "rs01"
#define MQTT_PASS   "$DEV_PASS"
EOF

echo "Done."
echo "  broker/credentials.txt   (dashboard login: user 'dashboard', pass $DASH_PASS)"
echo "  firmware/include/secrets.h  -> now set WIFI_SSID / WIFI_PASS in it"
echo "  Laptop IP detected: $IP  (ESP32 and laptop must be on the same Wi-Fi)"
